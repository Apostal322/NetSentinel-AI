"""DEDALE member-level manifest and (authorized) fetch of the green_internal Zeek logs.

Only selected members of `green_internal.zip` are fetched, by HTTP range requests at the
offsets in the publisher's central directory (reports/phase8l/dedale_zip_index.json, built by
dedale_zip_index.py). Each member's raw deflate stream is written unchanged inside a gzip
wrapper (`.gz`), and checked against the central directory's CRC32 and sizes.

Stages (docs/phase8l/DEDALE_PREREGISTRATION.md):
  A  calibration days D1-D14 (2024-12-23 .. 2025-01-05): conn_labeled.csv and dhcp.log
  B  evaluation days D15-D28 (2025-01-06 .. 2025-01-19): the same members; refused unless
     docs/phase8l/DEDALE_FREEZE.md is committed and records the pre-registration's SHA-256

Usage:
  python scripts/phase8l/dedale_fetch.py --manifest            # writes the manifest, no download
  python scripts/phase8l/dedale_fetch.py --stage A --download  # needs the user's authorization
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import subprocess
import sys
import time
import urllib.request
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INDEX = ROOT / "reports" / "phase8l" / "dedale_zip_index.json"
MANIFEST = ROOT / "reports" / "phase8l" / "dedale_manifest.json"
FREEZE = ROOT / "docs" / "phase8l" / "DEDALE_FREEZE.md"
PREREG = ROOT / "docs" / "phase8l" / "DEDALE_PREREGISTRATION.md"
OUT = ROOT / "data" / "raw" / "dedale" / "green_internal"
ARCHIVE = "green_internal.zip"
MEMBERS = ("conn_labeled.csv", "dhcp.log")
STAGES = {"A": range(1, 15), "B": range(15, 29)}
DAY = re.compile(r"^green_internal/D(\d+)_(\d{4}-\d\d-\d\d)_output_green_internal_Zeek/(.+)$")
CHUNK = 1 << 20


def select(index: dict, stage: str) -> list[dict]:
    """The stage's members, in day order, with their day number and date."""
    days = STAGES[stage]
    out = []
    for m in index[ARCHIVE]["members"]:
        g = DAY.match(m["name"])
        if g and int(g[1]) in days and g[3] in MEMBERS:
            out.append({**m, "day": int(g[1]), "date": g[2], "file": g[3]})
    out.sort(key=lambda m: (m["day"], m["file"]))
    if len(out) != len(days) * len(MEMBERS):
        raise SystemExit(f"stage {stage}: expected {len(days) * len(MEMBERS)} members, "
                         f"found {len(out)}")  # fmt: skip
    if any(m["method"] != 8 for m in out):
        raise SystemExit("a selected member is not deflate-compressed")
    return out


def manifest(index: dict) -> dict:
    arc = index[ARCHIVE]
    stages = {}
    for s in STAGES:
        ms = select(index, s)
        stages[s] = {
            "members": [
                {
                    k: m[k]
                    for k in (
                        "name",
                        "day",
                        "date",
                        "offset",
                        "compressed",
                        "uncompressed",
                        "crc32",
                    )
                }
                for m in ms
            ],  # fmt: skip
            "compressed_bytes": sum(m["compressed"] for m in ms),
            "uncompressed_bytes": sum(m["uncompressed"] for m in ms),
            "largest_uncompressed_member": max(m["uncompressed"] for m in ms),
        }
    return {"archive": ARCHIVE, "url": arc["url"], "dataverse_file_id": arc["dataverse_file_id"],
            "archive_size": arc["size"], "archive_md5": arc["md5"], "stages": stages}  # fmt: skip


def manifest_md(man: dict) -> str:
    rows = ["# DEDALE download manifest (generated by `scripts/phase8l/dedale_fetch.py --manifest`)",
            "", f"Source archive: `{man['archive']}` ({man['archive_size']:,} bytes, publisher MD5 "
            f"`{man['archive_md5']}`, Dataverse file id {man['dataverse_file_id']}).",
            f"Members are fetched by byte range from {man['url']}; each is checked against the "
            "CRC32 and sizes of the publisher's central directory. Its SHA-256 is recorded at "
            "download (`reports/phase8l/dedale_fetch_stage<S>.json`). No member-level MD5 is "
            "published, so the CRC32s are the expected hashes.", "",
            "Disk: members are stored compressed (about 384 MB + 396 MB); derived Parquet is at "
            "most 0.6 GB; uncompressed CSV is never kept. Plan for 1.5 GB; require 3 GB free.",
            ""]  # fmt: skip
    for s, v in man["stages"].items():
        rows += [f"## Stage {s}: {len(v['members'])} members, {v['compressed_bytes']:,} bytes "
                 f"to download, {v['uncompressed_bytes']:,} bytes uncompressed", "",
                 "| day | date | member | offset | compressed | uncompressed | CRC32 |",
                 "|---|---|---|---|---|---|---|"]  # fmt: skip
        rows += [f"| D{m['day']} | {m['date']} | `{m['name']}` | {m['offset']} | "
                 f"{m['compressed']:,} | {m['uncompressed']:,} | `{m['crc32']}` |"
                 for m in v["members"]]  # fmt: skip
        rows.append("")
    return "\n".join(rows)


def _range(url: str, start: int, end: int, total: int | None = None):
    req = urllib.request.Request(url, headers={"Range": f"bytes={start}-{end}"})
    r = urllib.request.urlopen(req, timeout=120)
    want = f"bytes {start}-{end}/"
    got = r.headers.get("Content-Range", "")
    if r.status != 206 or not got.startswith(want):
        r.close()
        raise RuntimeError(f"bad range response: {r.status} {got!r}")
    if total is not None and got[len(want) :] != str(total):
        r.close()
        raise RuntimeError(f"archive size changed: {got!r}, expected {total}")
    return r


def fetch_member(url: str, m: dict, dest: Path, opener=None, total: int | None = None) -> dict:
    """Write member m as dest (.gz around the publisher's deflate bytes); verify the local
    header's name, CRC32, sizes and the end of the deflate stream. Nothing is left on failure."""
    opener = opener or (lambda u, a, b: _range(u, a, b, total))
    name = m["name"].encode("utf-8")
    with opener(url, m["offset"], m["offset"] + 29 + len(name)) as r:
        hdr = r.read()
    if hdr[:4] != b"PK\x03\x04" or hdr[30:] != name:
        raise RuntimeError(f"{m['name']}: local header at offset {m['offset']} does not match")
    n, e = struct.unpack("<HH", hdr[26:30])
    start = m["offset"] + 30 + n + e
    crc, size, sha = 0, 0, hashlib.sha256()
    dec = zlib.decompressobj(-15)
    tmp = dest.with_suffix(dest.suffix + ".part")
    try:
        with opener(url, start, start + m["compressed"] - 1) as r, tmp.open("wb") as f:
            f.write(b"\x1f\x8b\x08\x00\x00\x00\x00\x00\x00\xff")  # gzip header, no name/mtime
            while chunk := r.read(CHUNK):
                sha.update(chunk)
                f.write(chunk)
                out = dec.decompress(chunk)
                crc, size = zlib.crc32(out, crc), size + len(out)
            out = dec.flush()
            crc, size = zlib.crc32(out, crc), size + len(out)
            f.write(struct.pack("<II", crc, size & 0xFFFFFFFF))
        got = {"crc32": f"{crc:08x}", "uncompressed": size}
        if (got["crc32"] != m["crc32"] or size != m["uncompressed"] or not dec.eof
                or dec.unused_data):  # fmt: skip
            raise RuntimeError(f"{m['name']}: integrity check failed {got}")
        tmp.replace(dest)
    finally:
        tmp.unlink(missing_ok=True)
    return {**got, "sha256_deflate": sha.hexdigest()}


HASH_LINE = re.compile(r"^([0-9a-f]{64})  (\S+)\s*$")


def lf_sha256(path: Path) -> str:
    """SHA-256 of a file with CRLF normalised to LF (the committed form of text files)."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def frozen_hashes(text: str) -> dict[str, str]:
    """`<sha256>  <repo-relative path>` lines of the freeze file."""
    return {g[2]: g[1] for line in text.splitlines() if (g := HASH_LINE.match(line))}


def _git_clean(rel: str) -> bool:
    """The path is committed and unchanged from HEAD (true for git-ignored files, which are
    covered by their hash alone)."""
    r = subprocess.run(["git", "-C", str(ROOT), "diff", "--quiet", "HEAD", "--", rel],
                       capture_output=True)  # fmt: skip
    return r.returncode == 0


def freeze_ok(freeze: Path | None = None, prereg: Path | None = None, check_git: bool = True,
              root: Path | None = None) -> bool:  # fmt: skip
    """N7: the freeze file exists, is committed and unchanged, lists the pre-registration, and
    every file it lists matches its recorded SHA-256 (LF-normalised) and, if tracked, HEAD."""
    freeze, prereg, root = freeze or FREEZE, prereg or PREREG, root or ROOT
    if not freeze.exists():
        return False
    hashes = frozen_hashes(freeze.read_text("utf-8"))
    try:
        rel_pre = prereg.resolve().relative_to(root.resolve()).as_posix()
        rel_freeze = freeze.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:  # outside the repository: cannot be the frozen file
        return False
    if rel_pre not in hashes:
        return False
    for rel, h in hashes.items():
        p = root / rel
        if not p.exists() or lf_sha256(p) != h:
            return False
    if check_git:
        tracked = subprocess.run(["git", "-C", str(root), "ls-files", "--error-unmatch", rel_freeze],
                                 capture_output=True).returncode == 0  # fmt: skip
        if not tracked or not all(_git_clean(r) for r in [rel_freeze, *hashes]):
            return False
    return True


def n8_passed(report: Path | None = None) -> bool:
    report = report or ROOT / "reports" / "phase8l" / "dedale_n8.json"
    return report.exists() and json.loads(report.read_text("utf-8")).get("outcome") == "PASS"


def download(stage: str) -> None:
    if stage == "B" and not (freeze_ok() and n8_passed()):
        raise SystemExit("stage B (evaluation days) is locked until docs/phase8l/DEDALE_FREEZE.md "
                         "is committed and verified (N7) and N8 has passed")  # fmt: skip
    man = json.loads(MANIFEST.read_text("utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    log = {}
    t0 = time.perf_counter()
    for m in man["stages"][stage]["members"]:
        dest = OUT / f"D{m['day']:02d}_{m['date']}_{Path(m['name']).name}.gz"
        log[m["name"]] = fetch_member(man["url"], m, dest, total=man["archive_size"])
        print(dest.name, log[m["name"]]["crc32"], flush=True)
    rep = ROOT / "reports" / "phase8l" / f"dedale_fetch_stage{stage}.json"
    rep.write_text(json.dumps({"stage": stage, "seconds": round(time.perf_counter() - t0, 1),
                               "members": log}, indent=1), "utf-8")  # fmt: skip


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", action="store_true")
    ap.add_argument("--stage", choices=sorted(STAGES))
    ap.add_argument("--download", action="store_true")
    a = ap.parse_args()
    if a.manifest:
        man = manifest(json.loads(INDEX.read_text("utf-8")))
        MANIFEST.write_text(json.dumps(man, indent=1), "utf-8")
        (ROOT / "docs" / "phase8l" / "DEDALE_MANIFEST.md").write_text(manifest_md(man), "utf-8")
        for s, v in man["stages"].items():
            print(
                s,
                len(v["members"]),
                f"{v['compressed_bytes'] / 1e6:.1f} MB compressed",
                f"{v['uncompressed_bytes'] / 1e6:.1f} MB raw",
            )
    elif a.stage and a.download:
        download(a.stage)
    else:
        sys.exit(ap.format_usage())


if __name__ == "__main__":
    main()
