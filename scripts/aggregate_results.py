"""Aggregate batch v1 runs into reports/experiments/results_v1.md (+ JSON + figures).

Every number printed comes from a run directory under runs/ and is tagged with its run id.
All metrics are VALIDATION metrics (the test split is untouched) on the sampled dataset with
prevalence weights (see docs/datasets/cse_cic_ids2018.md).
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import polars as pl  # noqa: E402

RUNS = Path("runs")
OUT = Path("reports/experiments")
FIG = Path("reports/figures")


def load_runs() -> pl.DataFrame:
    rows = []
    for d in sorted(p for p in RUNS.iterdir() if p.is_dir() and (p / "metrics.json").exists()):
        cfg_text = (d / "config.yaml").read_text("utf-8")
        import yaml

        cfg = yaml.safe_load(cfg_text)
        rows.append({"run_id": d.name, "dir": str(d), "experiment": cfg.get("experiment", ""),
                     "feature_set": cfg.get("feature_set", ""), "task": cfg.get("task", ""),
                     "protocol": cfg.get("split", {}).get("protocol", ""),
                     "metrics": json.loads((d / "metrics.json").read_text("utf-8"))})  # fmt: skip
    return pl.DataFrame(rows)


def latest(df: pl.DataFrame, experiment_prefix: str) -> list[dict]:
    """Latest run per (experiment, model-suffix) whose experiment starts with the prefix."""
    sub = [r for r in df.to_dicts() if r["experiment"].startswith(experiment_prefix)]
    best: dict[str, dict] = {}
    for r in sub:  # run ids sort by time
        model = r["run_id"].split(f"{r['experiment']}_", 1)[-1]
        best[f"{r['experiment']}|{model}"] = {**r, "model": model}
    return list(best.values())


def fmt(x, nd=4):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "-"
    return f"{x:.{nd}f}" if isinstance(x, float) else str(x)


def table(rows: list[dict], cols: list[tuple[str, str]]) -> str:
    head = "| " + " | ".join(h for h, _ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = ""
    for r in rows:
        body += "| " + " | ".join(fmt(r.get(k)) for _, k in cols) + " |\n"
    return head + body


def binary_section(df: pl.DataFrame) -> tuple[str, list[dict]]:
    runs = latest(df, "baseline_binary") + latest(df, "h5_")
    rows = []
    for r in runs:
        m = r["metrics"]
        err = json.loads(Path(r["dir"], "error_analysis_val.json").read_text("utf-8")) \
            if Path(r["dir"], "error_analysis_val.json").exists() else {}  # fmt: skip
        rows.append({
            "run_id": r["run_id"], "experiment": r["experiment"], "model": r["model"],
            "feature_set": r["feature_set"], "protocol": r["protocol"],
            "pr_auc": m.get("val/pr_auc"), "roc_auc": m.get("val/roc_auc"),
            "r_fpr1e3": m.get("val/recall_at_fpr_0.001"), "r_fpr1e2": m.get("val/recall_at_fpr_0.01"),
            "precision": m.get("val/precision"), "recall": m.get("val/recall"),
            "fpr": m.get("val/fpr"), "ece": m.get("val/ece"),
            "fit_s": m.get("cost/fit_seconds"), "us_row": m.get("cost/val_predict_us_per_row"),
            "peak_mb": m.get("cost/process_peak_rss_mb"),
            "train_rows": m.get("cost/train_rows"), "val_rows": m.get("cost/val_rows"),
            "recall_by_label": {x["label"]: x["recall"] for x in err.get("recall_by_label", [])},
        })  # fmt: skip
    return "", rows


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    df = load_runs()
    _, binary = binary_section(df)
    cols = [("run", "run_id"), ("model", "model"), ("features", "feature_set"),
            ("split", "protocol"), ("PR-AUC", "pr_auc"), ("ROC-AUC", "roc_auc"),
            ("recall@FPR1e-3", "r_fpr1e3"), ("recall@FPR1e-2", "r_fpr1e2"),
            ("precision@thr", "precision"), ("recall@thr", "recall"), ("ECE", "ece"),
            ("fit s", "fit_s"), ("peak MB", "peak_mb")]  # fmt: skip
    e1 = [r for r in binary if r["experiment"].startswith("baseline_binary")]
    h5 = [r for r in binary if r["experiment"].startswith("h5_")]
    # The episode-split LightGBM runs for flow / flow_ctx are the H5 reference rows.
    h5 += [r for r in e1 if r["model"] == "lightgbm" and r["feature_set"] in ("flow", "flow_ctx")]

    md = ["# Results v1 (validation split, measured)\n",
          "All numbers: VALIDATION split, CSE-CIC-IDS2018 stratified sample (benign 50k/day, attacks"
          " capped 25k per label-day), prevalence-weighted, infiltration excluded, label cleaning v1."
          " Generated by `scripts/aggregate_results.py`; each row names its run directory.\n",
          "## E1 - binary detection by model and feature set (episode split)\n",
          table(sorted(e1, key=lambda r: (r["feature_set"], r["model"])), cols),
          "\n## H5 - split protocol vs reported performance (LightGBM)\n",
          table(sorted(h5, key=lambda r: (r["feature_set"], r["protocol"])), cols)]  # fmt: skip

    # Per-label recall heatmap (LightGBM, episode split, per feature set).
    lgb = [r for r in e1 if r["model"] == "lightgbm" and r["recall_by_label"]]
    if lgb:
        labels = sorted({k for r in lgb for k in r["recall_by_label"]})
        mat = np.array([[r["recall_by_label"].get(lab, np.nan) for lab in labels] for r in lgb])
        fig, ax = plt.subplots(figsize=(1 + 0.7 * len(labels), 0.9 + 0.45 * len(lgb)))
        im = ax.imshow(mat, vmin=0, vmax=1, cmap="viridis", aspect="auto")
        ax.set_xticks(range(len(labels)), labels, rotation=45, ha="right", fontsize=8)
        ax.set_yticks(range(len(lgb)), [r["feature_set"] for r in lgb], fontsize=8)
        for i in range(mat.shape[0]):
            for j in range(mat.shape[1]):
                if not np.isnan(mat[i, j]):
                    ax.text(j, i, f"{mat[i, j]:.2f}", ha="center", va="center", fontsize=6,
                            color="white" if mat[i, j] < 0.5 else "black")  # fmt: skip
        fig.colorbar(im, ax=ax, fraction=0.03)
        ax.set_title(
            "LightGBM validation recall per attack label at FPR<=1e-3 threshold", fontsize=9
        )
        fig.tight_layout()
        fig.savefig(FIG / "binary_recall_by_label.png", dpi=140)
        plt.close(fig)
        md.append("\n![per-label recall](../figures/binary_recall_by_label.png)\n")

    # Multiclass.
    mc_rows = []
    for r in latest(df, "multiclass_"):
        p = Path(r["dir"], "multiclass_val.json")
        if not p.exists():
            continue
        mc = json.loads(p.read_text("utf-8"))
        mc_rows.append({"run_id": r["run_id"], "task": r["task"], "feature_set": r["feature_set"],
                        "macro_f1": mc["macro_f1"], "weighted_f1": mc["weighted_f1"],
                        "balanced_accuracy": mc["balanced_accuracy"],
                        "per_class": mc["per_class"]})  # fmt: skip
    if mc_rows:
        md += ["\n## E5 - attack-type classification (LightGBM, episode split)\n",
               table(mc_rows, [("run", "run_id"), ("task", "task"), ("features", "feature_set"),
                               ("macro-F1", "macro_f1"), ("weighted-F1", "weighted_f1"),
                               ("balanced acc", "balanced_accuracy")])]  # fmt: skip
        for r in mc_rows:
            md.append(f"\nPer-class ({r['task']}, {r['feature_set']}, `{r['run_id']}`):\n")
            md.append(table(
                [{"cls": k, **v} for k, v in r["per_class"].items()],
                [("class", "cls"), ("precision", "precision"), ("recall", "recall"),
                 ("F1", "f1"), ("val rows", "support_rows")],
            ))  # fmt: skip

    # Anomaly.
    an_rows = []
    for r in latest(df, "anomaly_"):
        m = r["metrics"]
        an_rows.append({"run_id": r["run_id"], "variant": r["model"], "feature_set": r["feature_set"],
                        "pr_auc": m.get("val/pr_auc"), "roc_auc": m.get("val/roc_auc"),
                        "r_fpr1e2": m.get("val/recall_at_fpr_0.01"),
                        "r_fpr1e3": m.get("val/recall_at_fpr_0.001"),
                        "contexts": m.get("cost/contexts"), "fit_s": m.get("cost/fit_seconds")})  # fmt: skip
    if an_rows:
        md += ["\n## E3 / H2 - anomaly detection, global vs service-conditioned\n",
               "Detectors fit on benign train flows only; score = benign-tail percentile.\n",
               table(sorted(an_rows, key=lambda r: (r["feature_set"], r["variant"])),
                     [("run", "run_id"), ("variant", "variant"), ("features", "feature_set"),
                      ("PR-AUC", "pr_auc"), ("ROC-AUC", "roc_auc"),
                      ("recall@FPR1e-2", "r_fpr1e2"), ("recall@FPR1e-3", "r_fpr1e3"),
                      ("contexts", "contexts"), ("fit s", "fit_s")])]  # fmt: skip

    # Open-set.
    os_rows = []
    for r in latest(df, "openset_"):
        m = r["metrics"]
        os_rows.append({"run_id": r["run_id"], "holdout": r["model"].replace("without_", ""),
                        "feature_set": r["feature_set"], **{k: m.get(k) for k in (
                            "unseen_rows", "supervised_recall", "anomaly_recall", "fused_recall",
                            "supervised_benign_val_fpr", "anomaly_benign_val_fpr",
                            "fused_benign_val_fpr")}})  # fmt: skip
    if os_rows:
        md += ["\n## E6 / H4 - unseen attack family (leave-one-family-out)\n",
               "Thresholds at benign-val FPR <= 1e-3 (fusion: 5e-4 each, OR rule). Evaluated on all "
               "rows of the held-out family + benign validation.\n",
               table(sorted(os_rows, key=lambda r: (r["feature_set"], r["holdout"])),
                     [("run", "run_id"), ("held-out family", "holdout"), ("features", "feature_set"),
                      ("rows", "unseen_rows"), ("supervised recall", "supervised_recall"),
                      ("anomaly recall", "anomaly_recall"), ("fused recall", "fused_recall"),
                      ("sup FPR", "supervised_benign_val_fpr"),
                      ("anom FPR", "anomaly_benign_val_fpr"),
                      ("fused FPR", "fused_benign_val_fpr")])]  # fmt: skip
        fig, axes = plt.subplots(1, 2, figsize=(10, 3.4), sharey=True)
        for ax, fs in zip(axes, ("flow", "flow_ctx"), strict=True):
            rs = sorted([r for r in os_rows if r["feature_set"] == fs], key=lambda r: r["holdout"])
            x = np.arange(len(rs))
            for k, (key, lab) in enumerate([("supervised_recall", "supervised"),
                                            ("anomaly_recall", "anomaly"),
                                            ("fused_recall", "fused")]):  # fmt: skip
                ax.bar(x + (k - 1) * 0.27, [r[key] for r in rs], 0.27, label=lab)
            ax.set_xticks(x, [r["holdout"] for r in rs], fontsize=8)
            ax.set_title(f"unseen-family recall ({fs})", fontsize=9)
            ax.set_ylim(0, 1)
        axes[0].set_ylabel("recall (prevalence-weighted)")
        axes[0].legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(FIG / "openset_recall.png", dpi=140)
        plt.close(fig)
        md.append("\n![open-set recall](../figures/openset_recall.png)\n")

    (OUT / "results_v1.md").write_text("\n".join(md), "utf-8")
    (OUT / "results_v1.json").write_text(
        json.dumps({"binary": binary, "multiclass": mc_rows, "anomaly": an_rows,
                    "openset": os_rows}, indent=2, default=str), "utf-8")  # fmt: skip
    print(f"wrote {OUT / 'results_v1.md'}")


if __name__ == "__main__":
    main()
